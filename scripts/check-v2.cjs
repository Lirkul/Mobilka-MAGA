const { chromium, expect: baseExpect } = require('@playwright/test');
const expect = baseExpect.configure({ timeout: 15000 });
const fs = require('node:fs/promises');

async function main() {
  const base = process.env.EXPO_WEB_URL || 'http://localhost:8081';
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 393, height: 852 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
  const button = (name) => page.getByRole('button', { name, exact: true });
  const visit = (path) => page.goto(new URL(path, base).href);
  const screenshot = (name) => page.screenshot({ path: `.expo/verification/v2-${name}.png`, animations: 'disabled' });
  async function menu(name) {
    await button(name === 'Моя библиотека' ? 'Открыть меню пользователя' : 'Открыть меню').click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await button(name === 'Настройки' ? 'Общие настройки' : name).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
  }
  try {
    await fs.mkdir('.expo/verification', { recursive: true });
    console.log('CHECK A: persistent shelves and reading');
    await visit('/');
    await expect(page.getByText('Популярное', { exact: true })).toBeVisible({ timeout: 60000 });
    await menu('Моя библиотека');
    await expect(page.getByRole('heading', { name: 'Моя библиотека', exact: true })).toBeVisible();
    await visit('/book/book_001');
    await button('В библиотеку').click();
    await page.getByRole('radio', { name: 'Читаю', exact: true }).click();
    await expect(button('Статус в библиотеке: Читаю')).toBeVisible();
    await page.reload();
    await expect(button('Статус в библиотеке: Читаю')).toBeVisible();
    await button('ЧИТАТЬ').click();
    await button('Следующая глава').click();
    await expect(page.getByRole('heading', { name: 'Глава 2. Тайный знак' })).toBeVisible();
    await page.getByTestId('reader-scroll').evaluate((node) => { node.scrollTop = (node.scrollHeight - node.clientHeight) * 0.6; });
    await expect(page.getByText('60% главы', { exact: true })).toBeVisible();
    // Allow the debounced write to become durable before simulating a hard reload.
    await page.waitForTimeout(750);
    await page.reload();
    await expect(page.getByText('60% главы', { exact: true })).toBeVisible();
    await expect.poll(() => page.getByTestId('reader-scroll').evaluate((node) => Math.round(node.scrollTop / (node.scrollHeight - node.clientHeight) * 100))).toBe(60);
    await menu('Главная');
    await expect(button('Продолжить чтение «Город под чёрным солнцем»')).toBeVisible();
    await expect(page.getByText('60%', { exact: true })).toBeVisible();
    await menu('Моя библиотека');
    await expect(page.getByTestId('book-result-book_001')).toBeVisible();
    await screenshot('library');
    await page.getByTestId('book-result-book_001').click();
    await button('Статус в библиотеке: Читаю').click();
    await page.getByRole('radio', { name: 'Прочту позже', exact: true }).click();
    await expect(button('Статус в библиотеке: Прочту позже')).toBeVisible();
    await page.reload();
    await expect(button('Статус в библиотеке: Прочту позже')).toBeVisible();
    await button('Статус в библиотеке: Прочту позже').click();
    await page.getByRole('radio', { name: 'Не интересно', exact: true }).click();
    await expect(button('Статус в библиотеке: Не интересно')).toBeVisible();
    await menu('Моя библиотека');
    await page.getByRole('button', { name: /^Выбрать полку:/ }).click();
    await page.getByRole('radio', { name: 'Не интересно', exact: true }).click();
    await page.getByTestId('book-result-book_001').click();
    await button('Статус в библиотеке: Не интересно').click();
    await page.getByRole('radio', { name: 'Читаю', exact: true }).click();
    await expect(button('Статус в библиотеке: Читаю')).toBeVisible();

    console.log('CHECK B: offline, local reading, retry, settings persistence');
    await menu('Настройки');
    await page.getByRole('switch', { name: 'Имитация отсутствия интернета' }).click();
    await expect(page.getByText('Сеть отключена', { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('switch', { name: 'Имитация отсутствия интернета' })).toBeChecked();
    await menu('Главная');
    await expect(page.getByText('Нет подключения к интернету', { exact: true })).toBeVisible();
    await expect(page.getByText('Последние книги', { exact: true })).toBeVisible();
    await button('ОБНОВИТЬ').click();
    await expect(page.getByText('Нет подключения к интернету', { exact: true })).toBeVisible();
    await screenshot('offline');
    await button('В БИБЛИОТЕКУ').click();
    await page.getByTestId('book-result-book_001').click();
    await button('ПРОДОЛЖИТЬ ЧТЕНИЕ').click();
    await expect(page.getByRole('heading', { name: 'Глава 2. Тайный знак' })).toBeVisible();
    await expect(page.getByText('60% главы', { exact: true })).toBeVisible();
    await menu('Настройки');
    await page.getByRole('switch', { name: 'Имитация отсутствия интернета' }).click();
    await expect(page.getByText('Сеть включена', { exact: true })).toBeVisible();
    await button('Назад').click();
    await expect(page.getByRole('heading', { name: 'Чтение', exact: true })).toBeVisible();
    await menu('Главная');
    await expect(page.getByText('Популярное', { exact: true })).toBeVisible();

    console.log('CHECK C: independent search, AND, empty, generic error and retry');
    const filters = { genres: ['Тёмное фэнтези', 'Боевая фантастика'], status: 'ongoing', access: 'free' };
    await visit(`/results?mode=discover&filters=${encodeURIComponent(JSON.stringify(filters))}`);
    await expect(page.getByText('Найдено книг: 2', { exact: true })).toBeVisible();
    await expect(page.getByTestId('book-result-book_001')).toBeVisible();
    await expect(page.getByTestId('book-result-book_019')).toBeVisible();
    await button('ФИЛЬТРЫ').click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await expect(button('Жанр: Темное фэнтези (+1)')).toBeVisible();
    await page.getByRole('textbox').fill('Протокол');
    await page.getByRole('textbox').press('Enter');
    await expect(page.getByTestId('book-result-book_004')).toBeVisible();
    await button('НОВЫЙ ПОИСК').click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await expect(page.getByRole('textbox')).toHaveValue('Протокол');
    await expect(button('Жанр: Темное фэнтези (+1)')).toBeVisible();
    await button('СБРОСИТЬ ВСЁ').click();
    await button('ПОДОБРАТЬ').click();
    await expect(page.getByText('Найдено книг: 19', { exact: true })).toBeVisible();
    await button('ФИЛЬТРЫ').click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.getByRole('textbox').fill('совершенно невозможный запрос');
    await button('Искать книги, авторов и посты').click();
    await expect(page.getByTestId('empty-state')).toBeVisible();
    await screenshot('empty');
    await visit('/results?mode=discover');
    await expect(page.getByText('Найдено книг: 19', { exact: true })).toBeVisible();
    await menu('Настройки');
    await button('Задержка ответа').click();
    await expect(page.getByText('1500 мс', { exact: true })).toBeVisible();
    await button('Ошибка следующего запроса').click();
    await button('Назад').click();
    await expect(page.getByText('Временная ошибка сервера. Повторите попытку.', { exact: true })).toBeVisible();
    await button('Повторить').click();
    await expect(page.getByText('Загрузка…', { exact: true })).toBeVisible();
    await expect(page.getByText('Найдено книг: 19', { exact: true })).toBeVisible();
    await menu('Настройки');
    await page.getByRole('switch', { name: 'Имитация отсутствия интернета' }).click();
    await expect(page.getByText('Сеть отключена', { exact: true })).toBeVisible();
    await button('Назад').click();
    await expect(page.getByTestId('offline-state')).toBeVisible();
    await button('ОБНОВИТЬ').click();
    await expect(page.getByText('Загрузка…', { exact: true })).toBeVisible();
    await expect(page.getByTestId('offline-state')).toBeVisible();
    await menu('Настройки');
    await page.getByRole('switch', { name: 'Имитация отсутствия интернета' }).click();
    await expect(page.getByText('Сеть включена', { exact: true })).toBeVisible();
    await button('Назад').click();
    await expect(page.getByText('Найдено книг: 19', { exact: true })).toBeVisible();
    await button('Обновить результаты').click();
    await expect(page.getByText('Загрузка…', { exact: true })).toBeVisible();
    await expect(page.getByText('Найдено книг: 19', { exact: true })).toBeVisible();
    await menu('Настройки');
    await button('Задержка ответа').click();
    await page.getByRole('switch', { name: 'Пустая выдача', exact: true }).click();
    await expect(page.getByRole('switch', { name: 'Пустая выдача', exact: true })).toBeChecked();
    await button('Назад').click();
    await expect(page.getByTestId('empty-state')).toBeVisible();
    await menu('Настройки');
    await page.getByRole('switch', { name: 'Пустая выдача', exact: true }).click();
    await expect(page.getByRole('switch', { name: 'Пустая выдача', exact: true })).not.toBeChecked();

    console.log('CHECK D: author tabs, notes, subscription, blog, artwork, reader settings');
    await visit('/author/author_01');
    await expect(page.getByText('Основная информация', { exact: true })).toBeVisible();
    await button('Подписаться на автора').click();
    await expect(button('Отписаться от автора')).toBeVisible();
    await page.getByRole('textbox', { name: 'Заметка об авторе' }).fill('Заметка для проверки сохранения');
    await button('Сохранить заметку').click();
    await expect(page.getByText('Заметка сохранена', { exact: true })).toBeVisible();
    await page.reload();
    await expect(button('Отписаться от автора')).toBeVisible();
    await expect(page.getByRole('textbox', { name: 'Заметка об авторе' })).toHaveValue('Заметка для проверки сохранения');
    await screenshot('author-profile');
    await page.getByRole('tab', { name: 'Произведения', exact: true }).click();
    await expect(button('Открыть книгу «Город под чёрным солнцем»')).toBeVisible();
    await screenshot('author-works');
    await button('Открыть книгу «Город под чёрным солнцем»').click();
    await expect(page.getByRole('heading', { name: 'Город под чёрным солнцем', exact: true })).toBeVisible();
    await button('Назад').click();
    await expect(page.getByRole('tab', { name: 'Произведения', exact: true })).toHaveAttribute('aria-selected', 'true');
    await page.getByRole('tab', { name: 'Блог', exact: true }).click();
    await expect(page.getByText('Записи в блогах · 1', { exact: true })).toBeVisible();
    await screenshot('author-blog');
    await button('Нравится пост «Новая глава и планы на ноябрь»').click();
    await expect(button('Нравится пост «Новая глава и планы на ноябрь»')).toHaveAttribute('aria-selected', 'true');
    await button('Читать дальше: Новая глава и планы на ноябрь').click();
    await expect(page.getByRole('heading', { name: 'Пост', exact: true })).toBeVisible();
    await button('Назад').click();
    await page.getByRole('tab', { name: 'Иллюстрации', exact: true }).click();
    await expect(page.getByText('Учебная галерея оформления книг', { exact: true })).toBeVisible();
    await screenshot('author-art');
    await button('Открыть иллюстрацию «Город под чёрным солнцем»').click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await button('Закрыть иллюстрацию').click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await visit('/reader/book_001');
    await button('Настройки чтения').click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await button('Увеличить шрифт').click();
    await expect(page.getByText('Размер шрифта: 20', { exact: true })).toBeVisible();
    await page.getByRole('radio', { name: 'Тёмная', exact: true }).click();
    await button('ГОТОВО').click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.reload();
    await button('Настройки чтения').click();
    await expect(page.getByText('Размер шрифта: 20', { exact: true })).toBeVisible();
    await expect(page.getByRole('radio', { name: 'Тёмная', exact: true })).toBeChecked();
    await screenshot('reader-settings');
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).toHaveCount(0);
    expect(errors).toEqual([]);
    console.log('PASS A/B/C/D: persistent shelves/progress/settings after F5; offline/local reading/retry; independent AND/search; loading/empty/error; author tabs/subscription/note/blog/art; reader settings; no browser errors.');
  } catch (error) {
    await screenshot('failure').catch(() => {});
    console.error('Browser errors:', errors);
    throw error;
  } finally { await browser.close(); }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
